-- Una fila por producto y corrida; los registros históricos nunca se sobreescriben entre corridas.
CREATE TABLE IF NOT EXISTS products (
 product_id TEXT PRIMARY KEY, product_url TEXT NOT NULL, product_name TEXT NOT NULL DEFAULT '',
 seller TEXT NOT NULL DEFAULT '', first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_seen TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS scrape_runs (
 run_id UUID PRIMARY KEY, started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 finished_at TIMESTAMPTZ, status TEXT NOT NULL CHECK(status IN ('RUNNING','COMPLETED','PARTIAL','FAILED')),
 discovered_count INTEGER NOT NULL DEFAULT 0, processed_count INTEGER NOT NULL DEFAULT 0,
 ok_count INTEGER NOT NULL DEFAULT 0, partial_count INTEGER NOT NULL DEFAULT 0,
 error_count INTEGER NOT NULL DEFAULT 0, error_message TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS price_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id UUID NOT NULL REFERENCES scrape_runs(run_id),
 product_id TEXT NOT NULL REFERENCES products(product_id),
 captured_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 price_current NUMERIC(14,2), price_previous NUMERIC(14,2),
 price_discount_pct NUMERIC(12,6), miles_current NUMERIC(14,2),
 miles_previous NUMERIC(14,2), miles_per_sol NUMERIC(14,4),
 miles_discount_pct NUMERIC(12,6), score NUMERIC(12,2),
 status TEXT NOT NULL CHECK(status IN ('OK','PARTIAL','ERROR')),
 notes TEXT NOT NULL DEFAULT '',
 UNIQUE(run_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_price_history_product_date ON price_history(product_id, captured_at DESC);
CREATE INDEX IF NOT EXISTS idx_price_history_run ON price_history(run_id);
CREATE INDEX IF NOT EXISTS idx_runs_started_at ON scrape_runs(started_at DESC);
